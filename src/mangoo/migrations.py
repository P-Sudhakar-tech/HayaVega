"""Small, auditable SQL migrations for Mangoo applications.

Migration files are Python modules named ``0001_description.py`` with an
``operations`` list.  Every operation is one SQL statement so a failed
migration can be rolled back with the database transaction that wraps it.
"""
from __future__ import annotations

from dataclasses import dataclass
from hashlib import sha256
import importlib.util
import inspect
from pathlib import Path
import re
from typing import Iterable

from .db import connect
from .models import Entity


class MigrationError(RuntimeError):
    pass


class MigrationIntegrityError(MigrationError):
    pass


class MigrationFormatError(MigrationError):
    pass


class MigrationGenerationError(MigrationError):
    pass


_MIGRATION_FILE = re.compile(r"^\d{4}_[a-zA-Z0-9_]+\.py$")


@dataclass(frozen=True)
class Migration:
    name: str
    operations: tuple[str, ...]
    checksum: str
    source: Path


@dataclass(frozen=True)
class MigrationStatus:
    name: str
    applied: bool


def _identifier(value: str) -> str:
    if not re.fullmatch(r"[A-Za-z_][A-Za-z0-9_]*", value):
        raise MigrationGenerationError(f"Unsafe schema identifier: {value}")
    return value


def create_table_operation(entity: type[Entity], engine: str = "sqlite3") -> str:
    """Return the deterministic CREATE TABLE statement for a declared entity."""
    definitions = []
    for name, column in entity._columns.items():
        definition = f"{_identifier(name)} {column.sql_type(engine)}"
        if not column.primary:
            if not column.nullable:
                definition += " NOT NULL"
            if column.unique:
                definition += " UNIQUE"
        definitions.append(definition)
    return f"CREATE TABLE {_identifier(entity.__table__)} ({', '.join(definitions)})"


def generate(models_module, migrations_directory: str | Path, engine: str = "sqlite3") -> Path | None:
    """Create an initial SQL migration from entities declared in ``models.py``.

    This deliberately generates only missing initial tables.  Altering a live
    schema needs an explicit migration until field-diff semantics are stable.
    """
    entities = [
        value for _, value in inspect.getmembers(models_module, inspect.isclass)
        if issubclass(value, Entity) and value is not Entity and value.__module__ == models_module.__name__
    ]
    if not entities:
        return None
    directory = Path(migrations_directory)
    directory.mkdir(parents=True, exist_ok=True)
    existing = [path for path in directory.iterdir() if _MIGRATION_FILE.fullmatch(path.name)]
    if existing:
        raise MigrationGenerationError(
            f"{directory} already has migrations; write follow-up schema changes explicitly."
        )
    operations = [create_table_operation(entity, engine) for entity in sorted(entities, key=lambda item: item.__table__)]
    target = directory / "0001_initial.py"
    target.write_text("# Generated by Mangoo; review before applying.\noperations = " + repr(operations) + "\n", encoding="utf-8")
    return target


def discover(directories: Iterable[str | Path]) -> list[Migration]:
    """Load and validate ordered migration modules from one or more folders."""
    migrations: list[Migration] = []
    names: set[str] = set()
    for directory in map(Path, directories):
        if not directory.exists():
            continue
        if not directory.is_dir():
            raise MigrationFormatError(f"Migration path is not a directory: {directory}")
        for source in sorted(directory.iterdir()):
            if not _MIGRATION_FILE.fullmatch(source.name):
                continue
            name = source.stem
            if name in names:
                raise MigrationFormatError(f"Duplicate migration name: {name}")
            spec = importlib.util.spec_from_file_location(f"_mangoo_migration_{name}", source)
            if spec is None or spec.loader is None:
                raise MigrationFormatError(f"Cannot load migration: {source}")
            module = importlib.util.module_from_spec(spec)
            spec.loader.exec_module(module)
            operations = getattr(module, "operations", None)
            if not isinstance(operations, (list, tuple)) or not operations or not all(isinstance(sql, str) and sql.strip() for sql in operations):
                raise MigrationFormatError(f"{source.name} must define a non-empty list of SQL string operations.")
            if any(";" in sql.strip().rstrip(";") for sql in operations):
                raise MigrationFormatError(f"{source.name} operations must contain exactly one SQL statement.")
            names.add(name)
            text = source.read_bytes()
            migrations.append(Migration(name, tuple(operations), sha256(text).hexdigest(), source))
    return sorted(migrations, key=lambda migration: migration.name)


def _prepare_history(connection) -> None:
    connection.execute("CREATE TABLE IF NOT EXISTS mangoo_migrations (name TEXT PRIMARY KEY, checksum TEXT NOT NULL, applied_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP)")


def _history(connection) -> dict[str, str]:
    _prepare_history(connection)
    # DDL may open an implicit transaction on PostgreSQL/MySQL.  Finish that
    # setup work before ``apply`` starts an explicit migration transaction.
    connection.commit()
    return {row["name"]: row["checksum"] for row in connection.execute("SELECT name, checksum FROM mangoo_migrations").fetchall()}


def status(database, directories: Iterable[str | Path]) -> list[MigrationStatus]:
    migrations = discover(directories)
    connection = connect(database)
    try:
        applied = _history(connection)
        known = {migration.name for migration in migrations}
        missing = set(applied) - known
        if missing:
            raise MigrationIntegrityError(f"Applied migration files are missing: {', '.join(sorted(missing))}")
        for migration in migrations:
            if migration.name in applied and applied[migration.name] != migration.checksum:
                raise MigrationIntegrityError(f"Applied migration was altered: {migration.name}")
        return [MigrationStatus(migration.name, migration.name in applied) for migration in migrations]
    finally:
        connection.close()


def apply(database, directories: Iterable[str | Path]) -> list[str]:
    """Apply unapplied migrations.  Each migration is one all-or-nothing unit."""
    migrations = discover(directories)
    connection = connect(database)
    try:
        applied = _history(connection)
        known = {migration.name for migration in migrations}
        missing = set(applied) - known
        if missing:
            raise MigrationIntegrityError(f"Applied migration files are missing: {', '.join(sorted(missing))}")
        completed: list[str] = []
        for migration in migrations:
            checksum = applied.get(migration.name)
            if checksum is not None:
                if checksum != migration.checksum:
                    raise MigrationIntegrityError(f"Applied migration was altered: {migration.name}")
                continue
            try:
                with connection.atomic():
                    for operation in migration.operations:
                        connection.execute(operation)
                    connection.execute("INSERT INTO mangoo_migrations (name, checksum) VALUES (?, ?)", (migration.name, migration.checksum))
            except Exception as error:
                raise MigrationError(f"Migration {migration.name} failed: {error}") from error
            completed.append(migration.name)
        return completed
    finally:
        connection.close()
