"""Built-in OpenAPI documents and Swagger UI for Mangoo applications."""
from __future__ import annotations

from .response import Response, json_response
from .routing import Route


def openapi_document(routes: list[Route], *, title: str = "Mangoo API", version: str = "0.1.0") -> dict:
    """Build an OpenAPI 3.0 document from the application's registered routes."""
    paths: dict[str, dict] = {}
    for route in routes:
        if route.pattern in {"docs", "openapi.json"} or not route.is_api:
            continue
        path_item = paths.setdefault(f"/{route.pattern}", {})
        for method in route.methods:
            operation = {
                "summary": route.pattern.replace("/", " ").replace("-", " ").title(),
                "responses": {"200": {"description": "Successful response"}},
            }
            if method in {"POST", "PUT", "PATCH"}:
                operation["requestBody"] = {
                    "required": False,
                    "content": {"application/json": {"schema": {"type": "object"}}},
                }
            path_item[method.lower()] = operation
    return {
        "openapi": "3.0.3",
        "info": {"title": title, "version": version, "description": "Built-in API documentation generated by Mangoo."},
        "paths": paths,
    }


def swagger_ui(request) -> Response:
    """Return a small Swagger UI shell backed by the local OpenAPI endpoint."""
    return Response(
        """<!doctype html><html lang=\"en\"><head><meta charset=\"utf-8\"><meta name=\"viewport\" content=\"width=device-width, initial-scale=1\"><title>Mangoo API documentation</title><link rel=\"stylesheet\" href=\"https://unpkg.com/swagger-ui-dist@5/swagger-ui.css\"></head><body><div id=\"swagger-ui\"></div><script src=\"https://unpkg.com/swagger-ui-dist@5/swagger-ui-bundle.js\"></script><script>SwaggerUIBundle({url:'/openapi.json',dom_id:'#swagger-ui'});</script><noscript>Open <a href=\"/openapi.json\">the OpenAPI document</a> to view the API schema.</noscript></body></html>"""
    )


def documentation_routes(routes: list[Route]) -> list[Route]:
    """Return the built-in OpenAPI JSON and Swagger UI routes when unused."""
    registered = {route.pattern for route in routes}
    builtins: list[Route] = []
    if "openapi.json" not in registered:
        builtins.append(Route("openapi.json", lambda request: json_response(openapi_document(routes)), is_api=False))
    if "docs" not in registered:
        builtins.append(Route("docs", swagger_ui, is_api=False))
    return builtins
