"""Built-in OpenAPI documents and Swagger UI for Hayavega applications."""

from __future__ import annotations

from typing import Any

from .response import Response, json_response
from .routing import Route

ERROR_SCHEMA = {"type": "object", "properties": {"detail": {"type": "string"}}, "required": ["detail"]}

_STANDARD_ERROR_DESCRIPTIONS = {
    400: "The request body was missing required fields or was otherwise invalid.",
    401: "Authentication is required.",
    403: "The caller does not have permission to perform this action.",
    429: "Too many requests; retry after a delay.",
}


def _error_response(status: int) -> dict:
    return {"description": _STANDARD_ERROR_DESCRIPTIONS[status], "content": {"application/json": {"schema": ERROR_SCHEMA}}}


def _response_entry(spec: dict) -> dict:
    entry = {"description": spec.get("description", "Response")}
    if "schema" in spec:
        entry["content"] = {"application/json": {"schema": spec["schema"]}}
    return entry


def openapi_document(routes: list[Route], *, title: str = "Hayavega API", version: str = "0.1.0") -> dict:
    """Build an OpenAPI 3.0 document from the application's registered routes.

    A route declares its own request/response shape with ``api_route(...,
    secured=..., request_schema=..., responses=...)``; routes that omit these
    fall back to the previous generic ``{"type": "object"}`` schema, so this
    stays backward compatible with routes that don't describe themselves.
    """
    paths: dict[str, dict] = {}
    for route in routes:
        if route.pattern in {"docs", "openapi.json"} or not route.is_api:
            continue
        path_item = paths.setdefault(f"/{route.pattern}", {})
        for method in route.methods:
            if route.responses:
                responses = {str(code): _response_entry(spec) for code, spec in route.responses.items()}
            else:
                responses = {"200": {"description": "Successful response", "content": {"application/json": {"schema": {"type": "object"}}}}}
            if method in {"POST", "PUT", "PATCH"} and "400" not in responses:
                responses["400"] = _error_response(400)
            if route.secured:
                responses.setdefault("401", _error_response(401))
            operation: dict[str, Any] = {
                "summary": route.pattern.replace("/", " ").replace("-", " ").title(),
                "responses": responses,
            }
            if method in {"POST", "PUT", "PATCH"}:
                schema = route.request_schema or {"type": "object"}
                operation["requestBody"] = {"required": route.request_schema is not None, "content": {"application/json": {"schema": schema}}}
            if route.secured:
                operation["security"] = [{"bearerAuth": []}]
            path_item[method.lower()] = operation
    return {
        "openapi": "3.0.3",
        "info": {"title": title, "version": version, "description": "Built-in API documentation generated by Hayavega."},
        "paths": paths,
        "components": {
            "securitySchemes": {"bearerAuth": {"type": "http", "scheme": "bearer", "description": "A session token from POST /api/auth/login, sent as `Authorization: Bearer <token>`."}},
            "schemas": {"Error": ERROR_SCHEMA},
        },
    }


def swagger_ui(request) -> Response:
    """Return a small Swagger UI shell backed by the local OpenAPI endpoint."""
    return Response(
        """<!doctype html><html lang=\"en\"><head><meta charset=\"utf-8\"><meta name=\"viewport\" content=\"width=device-width, initial-scale=1\"><title>Hayavega API documentation</title><link rel=\"stylesheet\" href=\"https://unpkg.com/swagger-ui-dist@5/swagger-ui.css\"></head><body><div id=\"swagger-ui\"></div><script src=\"https://unpkg.com/swagger-ui-dist@5/swagger-ui-bundle.js\"></script><script>SwaggerUIBundle({url:'/openapi.json',dom_id:'#swagger-ui'});</script><noscript>Open <a href=\"/openapi.json\">the OpenAPI document</a> to view the API schema.</noscript></body></html>"""
    )


def documentation_routes(routes: list[Route], *, title: str = "Hayavega API", version: str = "0.1.0") -> list[Route]:
    """Return the built-in OpenAPI JSON and Swagger UI routes when unused."""
    registered = {route.pattern for route in routes}
    builtins: list[Route] = []
    if "openapi.json" not in registered:
        builtins.append(Route("openapi.json", lambda request: json_response(openapi_document(routes, title=title, version=version)), is_api=False))
    if "docs" not in registered:
        builtins.append(Route("docs", swagger_ui, is_api=False))
    return builtins
