"""Small, auditable SQL migrations for Hayavega applications.

Migration files are Python modules named ``0001_description.py`` with an
``operations`` list.  Every operation is one SQL statement so a failed
migration can be rolled back with the database transaction that wraps it.
"""

from __future__ import annotations

import importlib.util
import inspect
import os
import re
import warnings
from collections.abc import Iterable
from dataclasses import dataclass
from hashlib import sha256
from pathlib import Path
from typing import TYPE_CHECKING, cast

from .db import connect
from .models import Entity

if TYPE_CHECKING:
    from .addons.signals import SignalBus


class MigrationError(RuntimeError):
    pass


class MigrationIntegrityError(MigrationError):
    pass


class MigrationFormatError(MigrationError):
    pass


class MigrationGenerationError(MigrationError):
    pass


_MIGRATION_FILE = re.compile(r"^\d{4}_[a-zA-Z0-9_]+\.py$")


@dataclass(frozen=True)
class Migration:
    name: str
    operations: tuple[str, ...]
    dependencies: tuple[str, ...]
    checksum: str
    source: Path


@dataclass(frozen=True)
class MigrationStatus:
    name: str
    applied: bool


def _identifier(value: str) -> str:
    if not re.fullmatch(r"[A-Za-z_][A-Za-z0-9_]*", value):
        raise MigrationGenerationError(f"Unsafe schema identifier: {value}")
    return value


def _column_definition(name: str, column, engine: str) -> str:
    """Return the deterministic ``name TYPE [NOT NULL] [UNIQUE]`` fragment for a column."""
    definition = f"{_identifier(name)} {column.sql_type(engine)}"
    if not column.primary:
        if not column.nullable:
            definition += " NOT NULL"
        if column.unique:
            definition += " UNIQUE"
    return definition


def create_table_operation(entity: type[Entity], engine: str = "sqlite3") -> str:
    """Return the deterministic CREATE TABLE statement for a declared entity."""
    definitions = [_column_definition(name, column, engine) for name, column in entity._columns.items()]
    return f"CREATE TABLE {_identifier(entity.__table__)} ({', '.join(definitions)})"


def generate(models_module, migrations_directory: str | Path, engine: str = "sqlite3") -> Path | None:
    """Create an initial SQL migration from entities declared in ``models.py``.

    The generator creates an initial migration, then supports only additive,
    nullable columns. New tables, column removals, and column alterations
    (type, nullability, or uniqueness changes on an existing column) are
    detected and rejected here rather than silently ignored, since they
    remain explicit SQL migrations for review.
    """
    entities = [value for _, value in inspect.getmembers(models_module, inspect.isclass) if issubclass(value, Entity) and value is not Entity and value.__module__ == models_module.__name__]
    if not entities:
        return None
    directory = Path(migrations_directory)
    directory.mkdir(parents=True, exist_ok=True)
    # Sorted by filename (so numerically, since names are zero-padded) --
    # `_declared_columns` below must see each table's CREATE TABLE before any
    # ALTER TABLE ADD COLUMN that follows it, or the added column is silently
    # dropped. `Path.iterdir()` makes no ordering guarantee; unlike NTFS,
    # ext4 does not happen to return entries in creation order, so this was
    # silently broken on Linux (and any filesystem without that coincidence)
    # while appearing to work on Windows.
    existing = sorted((path for path in directory.iterdir() if _MIGRATION_FILE.fullmatch(path.name)), key=lambda path: path.name)
    if not existing:
        operations = [create_table_operation(entity, engine) for entity in sorted(entities, key=lambda item: item.__table__)]
        target = directory / "0001_initial.py"
        target.write_text("# Generated by Hayavega; review before applying.\ndependencies = []\noperations = " + repr(operations) + "\n", encoding="utf-8")
        return target
    known = _declared_columns(existing)
    operations = []
    for entity in sorted(entities, key=lambda item: item.__table__):
        table = _identifier(entity.__table__)
        if table not in known:
            raise MigrationGenerationError(f"New table {table} needs an explicit reviewed migration.")
        removed = set(known[table]) - set(entity._columns)
        if removed:
            raise MigrationGenerationError(f"Removed columns on {table} need an explicit reviewed migration: {', '.join(sorted(removed))}.")
        for name, column in entity._columns.items():
            declared_definition = _column_definition(name, column, engine)
            if name in known[table]:
                if known[table][name] != declared_definition:
                    raise MigrationGenerationError(f"Field alteration on {table}.{name} needs an explicit reviewed migration (applied: '{known[table][name]}', declared: '{declared_definition}').")
                continue
            if not column.nullable:
                raise MigrationGenerationError(f"New column {table}.{name} must be nullable; backfill required columns in an explicit migration.")
            operations.append(f"ALTER TABLE {table} ADD COLUMN {declared_definition}")
    if not operations:
        return None
    number = max(int(path.name[:4]) for path in existing) + 1
    target = directory / f"{number:04d}_auto.py"
    dependencies = [max(existing, key=lambda path: path.name).stem]
    target.write_text("# Generated by Hayavega; review before applying.\ndependencies = " + repr(dependencies) + "\noperations = " + repr(operations) + "\n", encoding="utf-8")
    return target


def _declared_columns(paths: Iterable[Path]) -> dict[str, dict[str, str]]:
    """Extract the conservative schema known to generator-produced SQL.

    Each table maps its column names to the full ``name TYPE ...`` definition
    text so ``generate`` can detect a type, nullability, or uniqueness change
    on a column that already exists, not just its presence.
    """
    tables: dict[str, dict[str, str]] = {}
    create = re.compile(r"^CREATE TABLE ([A-Za-z_][A-Za-z0-9_]*) \((.*)\)$", re.DOTALL)
    add_column = re.compile(r"^ALTER TABLE ([A-Za-z_][A-Za-z0-9_]*) ADD COLUMN ([A-Za-z_][A-Za-z0-9_]*) (.+)$", re.DOTALL)
    for path in paths:
        namespace: dict[str, object] = {}
        exec(compile(path.read_bytes(), path, "exec"), namespace)
        for sql in cast(list, namespace.get("operations", [])):
            match = create.fullmatch(sql)
            if match:
                tables[match.group(1)] = {part.strip().split()[0]: part.strip() for part in match.group(2).split(",")}
                continue
            match = add_column.fullmatch(sql)
            if match and match.group(1) in tables:
                tables[match.group(1)][match.group(2)] = f"{match.group(2)} {match.group(3)}"
    return tables


def migration_directories(settings) -> list[str]:
    """Return each installed app's ``migrations`` directory, in declaration order.

    Shared by `manage.py applymigrations`/`migrationstatus`/`newmigration`
    and the `diagnose` command's pending-migration check, so both walk
    `settings.installed_apps` identically rather than maintaining two
    copies of the same import-and-locate logic.
    """
    directories: list[str] = []
    for app in settings.installed_apps:
        module = __import__(app, fromlist=["__file__"])
        module_file = getattr(module, "__file__", None)
        if module_file:
            directories.append(os.path.join(os.path.dirname(module_file), "migrations"))
    return directories


def discover(directories: Iterable[str | Path]) -> list[Migration]:
    """Load and validate ordered migration modules from one or more folders."""
    migrations: list[Migration] = []
    names: set[str] = set()
    for directory in map(Path, directories):
        if not directory.exists():
            continue
        if not directory.is_dir():
            raise MigrationFormatError(f"Migration path is not a directory: {directory}")
        for source in sorted(directory.iterdir()):
            if not _MIGRATION_FILE.fullmatch(source.name):
                continue
            name = source.stem
            if name in names:
                raise MigrationFormatError(f"Duplicate migration name: {name}")
            spec = importlib.util.spec_from_file_location(f"_hayavega_migration_{name}", source)
            if spec is None or spec.loader is None:
                raise MigrationFormatError(f"Cannot load migration: {source}")
            module = importlib.util.module_from_spec(spec)
            spec.loader.exec_module(module)
            operations = getattr(module, "operations", None)
            if not isinstance(operations, (list, tuple)) or not operations or not all(isinstance(sql, str) and sql.strip() for sql in operations):
                raise MigrationFormatError(f"{source.name} must define a non-empty list of SQL string operations.")
            if any(";" in sql.strip().rstrip(";") for sql in operations):
                raise MigrationFormatError(f"{source.name} operations must contain exactly one SQL statement.")
            dependencies = getattr(module, "dependencies", [])
            if not isinstance(dependencies, (list, tuple)) or not all(isinstance(item, str) and _MIGRATION_FILE.fullmatch(item + ".py") for item in dependencies):
                raise MigrationFormatError(f"{source.name} dependencies must be a list of migration names.")
            names.add(name)
            text = source.read_bytes()
            migrations.append(Migration(name, tuple(operations), tuple(dependencies), sha256(text).hexdigest(), source))
    by_name = {migration.name: migration for migration in migrations}
    for migration in migrations:
        absent = set(migration.dependencies) - set(by_name)
        if absent:
            raise MigrationFormatError(f"{migration.name} has missing dependencies: {', '.join(sorted(absent))}")
    ordered: list[Migration] = []
    remaining = dict(by_name)
    while remaining:
        ready = [item for item in remaining.values() if set(item.dependencies).issubset({done.name for done in ordered})]
        if not ready:
            raise MigrationFormatError("Migration dependencies contain a cycle.")
        for migration in sorted(ready, key=lambda item: item.name):
            ordered.append(migration)
            del remaining[migration.name]
    return ordered


def _prepare_history(connection) -> None:
    # VARCHAR (not TEXT) for the primary key: MySQL cannot index a TEXT/BLOB
    # column without an explicit prefix length. TIMESTAMP (not TEXT) for
    # applied_at: MySQL rejects CURRENT_TIMESTAMP as a default on a non-
    # temporal column type ("Invalid default value"). Both are accepted by
    # SQLite (type affinity, not enforcement) and PostgreSQL unchanged.
    connection.execute("CREATE TABLE IF NOT EXISTS hayavega_migrations (name VARCHAR(255) PRIMARY KEY, checksum TEXT NOT NULL, applied_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP)")


def _history(connection) -> dict[str, str]:
    _prepare_history(connection)
    # DDL may open an implicit transaction on PostgreSQL/MySQL.  Finish that
    # setup work before ``apply`` starts an explicit migration transaction.
    connection.commit()
    return {row["name"]: row["checksum"] for row in connection.execute("SELECT name, checksum FROM hayavega_migrations").fetchall()}


def status(database, directories: Iterable[str | Path]) -> list[MigrationStatus]:
    migrations = discover(directories)
    connection = connect(database)
    try:
        applied = _history(connection)
        known = {migration.name for migration in migrations}
        missing = set(applied) - known
        if missing:
            raise MigrationIntegrityError(f"Applied migration files are missing: {', '.join(sorted(missing))}")
        for migration in migrations:
            if migration.name in applied and applied[migration.name] != migration.checksum:
                raise MigrationIntegrityError(f"Applied migration was altered: {migration.name}")
        return [MigrationStatus(migration.name, migration.name in applied) for migration in migrations]
    finally:
        connection.close()


def apply(database, directories: Iterable[str | Path], *, signals: SignalBus | None = None, pulse: SignalBus | None = None) -> list[str]:
    """Apply unapplied migrations.  Each migration is one all-or-nothing unit.

    ``signals``, when given a ``SignalBus``, publishes ``migration.applied``
    for each migration after its transaction has committed. ``pulse`` is a
    deprecated alias for ``signals``.
    """
    if pulse is not None:
        warnings.warn("`pulse=` is deprecated; use `signals=` instead.", DeprecationWarning, stacklevel=2)
        signals = pulse if signals is None else signals
    migrations = discover(directories)
    connection = connect(database)
    try:
        applied = _history(connection)
        known = {migration.name for migration in migrations}
        missing = set(applied) - known
        if missing:
            raise MigrationIntegrityError(f"Applied migration files are missing: {', '.join(sorted(missing))}. Restore the missing file(s) from version control, or remove their rows from the hayavega_migrations table if the removal was intentional.")
        completed: list[str] = []
        for migration in migrations:
            checksum = applied.get(migration.name)
            if checksum is not None:
                if checksum != migration.checksum:
                    raise MigrationIntegrityError(f"Applied migration was altered: {migration.name} ({migration.source}). An already-applied migration must never be edited -- revert {migration.source} to its applied contents, or write a new migration for the change instead.")
                continue
            try:
                with connection.atomic():
                    for operation in migration.operations:
                        connection.execute(operation)
                    connection.execute("INSERT INTO hayavega_migrations (name, checksum) VALUES (?, ?)", (migration.name, migration.checksum))
            except Exception as error:
                raise MigrationError(f"Migration {migration.name} ({migration.source}) failed: {error}. Fix the operation in {migration.source} and re-run -- this migration was rolled back, no partial schema change was committed.") from error
            if signals is not None:
                signals.publish("migration.applied", data={"name": migration.name})
            completed.append(migration.name)
        return completed
    finally:
        connection.close()
